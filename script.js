const grid = document.querySelector(".grid");
const dim = grid.getBoundingClientRect();
const tracker = Array.from({ length: 8 }, () => new Array(8).fill(null));
const cells = new Map();
let RUNNING = true;
let turn = 0;
let active = [];
let next_moves = [];

//render the squares
flag = false;
for (let i = 0; i < 8; i++) {
  for (let j = 0; j < 8; j++) {
    const el = document.createElement("li");
    el.classList.add(".cell");
    el.classList.add();
    cells.set(`${i},${j}`, el);
    if (i % 2 == 0) {
      flag == true ? el.classList.add("even") : el.classList.add("odd");
    } else {
      flag == true ? el.classList.add("odd") : el.classList.add("even");
    }
    flag = !flag;
    grid.append(el);
  }
}

const rook = new Rook("rook", "white", 4, 4);
tracker[4][4] = rook;
const pawn = new Pawn("pawn", "white", 6, 4);
tracker[6][4] = pawn;
const knight = new Knight("knight", "white", 7, 3);
tracker[7][3] = knight;

for (let i = 0; i < 8; i++) {
  for (let j = 0; j < 8; j++) {
    if (tracker[i][j]) {
      const start_point = cells.get(`${i},${j}`);
      const img = document.createElement("svg");
      img.className = "piece";
      img.innerHTML = tracker[i][j].icon;
      start_point.appendChild(img);
    }
  }
}

document.querySelector(".board").addEventListener("click", (e) => {
  const [row, col] = getCell(e);
  const cell = cells.get(`${row},${col}`);
  const obj = active.length ? tracker[active[0]][active[1]] : '';

  if (active.length !== 0 && move(row, col)) {
    renderPiece(row, col, obj);
    cleanUpBoard(true);
  } else if (active.length !== 0) {
    cleanUpBoard(false);
    renderNextMoves(row, col, cell);
  } else if (tracker[row][col]) {
    renderNextMoves(row, col, cell);
  }
});

//returns row and column of clicked cell
function getCell(e) {
  let clickX = e.clientX - dim.left;
  let clickY = e.clientY - dim.top;
  const row = Math.floor(clickY / 50);
  const col = Math.floor(clickX / 50);
  return [row, col];
}

//resets next moves and active
function cleanUpBoard(valid) {
  const node = cells.get(`${active[0]},${active[1]}`);
  node.classList.remove("active");

  if (next_moves) {
    while (next_moves.length !== 0) {
      next_moves.pop().node.classList.remove("active");
    }
  }

  if (valid) {
    node.removeChild(node.children[0]);
  }

  active = [];
}

// renders piece into new location
function renderPiece(row, col, obj) {
  const start_point = cells.get(`${row},${col}`);
  const img = document.createElement("svg");
  img.className = "piece";
  img.innerHTML = `${obj.icon}`;
  start_point.appendChild(img);
}

// renders next moves and active cells
function renderNextMoves(row, col, cell) {
  next_moves = tracker[row][col].next_move();
  console.log(next_moves);
  next_moves.forEach((el) => {
    el.node.classList.add("active");
  });

  cell.classList.add("active");
  active = [row, col];
}

// changes the object's row and col
// makes change in tracker
// Calls cleanUpBoard, and renderPiece
function move(row, col) {
  
  for (let i = 0; i < next_moves.length; i++) {
    if (next_moves[i].next_row === row && next_moves[i].next_col === col) {
      const obj = tracker[active[0]][active[1]];
      obj.R = row;
      obj.C = col;
      tracker[active[0]][active[1]] = null;
      tracker[row][col] = obj;
      return true;
    }
  }
  return false;
}
